const DICTIONARIES: Record<Locale, Record<keyof typeof en, string>> = { en, fr };
export type MessageKey = keyof typeof en;

/** Translate a key, with `{name}` placeholders. Unknown locale falls back to English. */
export function t(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}): string {
  const text = DICTIONARIES[locale]?.[key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}
